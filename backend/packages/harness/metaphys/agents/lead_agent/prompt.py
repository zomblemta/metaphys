"""lead agent 的系统提示词。

**这里是请求，不是机制。** 提示词能显著降低模型自行推算的概率，但不能把它降到零
—— 真正的保障是 :class:`~metaphys.middlewares.grounding.GroundingMiddleware`
（核验输出）与依赖层护栏（`middlewares/` 根本 import 不到历法库）。两者都要有：
护栏决定"做不到"，提示词决定"不去做"，核验决定"做了会被发现"。

**模板是静态的。** 当前日期、用户称呼一类运行动态上下文**不进**系统提示词 ——
一旦进去，前缀缓存每轮失效，长对话的成本与首字延迟都会明显变差。动态信息应通过
state 或消息传递。

**星盘这条链路上，本文件的分量比八字更重。** 八字的核验能扫 60 甲子（普通中文
散文几乎不会自然出现干支），所以"编了一定被抓"；星盘的词表是**开放**的 ——
「双子座」是日常词汇，核验只能认结构化断言，模型顺口提一个星座抓不住（详见
``M3-FINDINGS.md``）。机制兜不住的底，只能由提示词兜：铁律一里星盘那一节
写得比八字细，是**刻意**的，不要为了整齐把它压缩回去。

**组装用 join 而非 str.format。** 提示词里大量出现 JSON 示例与花括号，`format`
会把它们当占位符吃掉；join 没有这个问题，也不需要转义。
"""

from __future__ import annotations

